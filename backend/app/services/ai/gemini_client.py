"""Google Gemini client provider implementation with structured JSON output."""
import json
from typing import Type, TypeVar
import httpx
from pydantic import BaseModel
from app.core.config import get_settings
from app.core.errors import AppError
from app.core.logging import get_logger
from app.services.ai.base import LLMClient

log = get_logger("gemini_client")
settings = get_settings()
T = TypeVar("T", bound=BaseModel)


class GeminiClient(LLMClient):
    def __init__(self, api_key: str = ""):
        self.api_key = api_key or settings.gemini_api_key

    async def generate_structured(
        self,
        prompt: str,
        response_schema: Type[T],
        system_instruction: str = "",
        max_tokens: int = 1500,
        temperature: float = 0.2
    ) -> T:
        if not self.api_key:
            raise AppError("Gemini API key not configured", status_code=503)

        schema_json = json.dumps(response_schema.model_json_schema())
        system_prompt = f"{system_instruction}\nStrict requirement: Output only valid JSON conforming to this schema:\n{schema_json}"

        url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={self.api_key}"
        payload = {
            "contents": [
                {
                    "parts": [
                        {"text": f"{system_prompt}\n\nTask:\n{prompt}"}
                    ]
                }
            ],
            "generationConfig": {
                "temperature": temperature,
                "maxOutputTokens": max_tokens,
                "responseMimeType": "application/json"
            }
        }

        async with httpx.AsyncClient(timeout=30.0) as client:
            resp = await client.post(url, json=payload)
            if resp.status_code != 200:
                log.error("gemini_api_error", status=resp.status_code, body=resp.text)
                raise AppError(f"Gemini error: {resp.text}", status_code=502)

            data = resp.json()
            candidates = data.get("candidates", [])
            if not candidates:
                raise AppError("No response generated by Gemini", status_code=502)

            text_content = candidates[0].get("content", {}).get("parts", [{}])[0].get("text", "{}")
            # Clean markdown code blocks if present
            if text_content.startswith("```json"):
                text_content = text_content[7:]
            if text_content.startswith("```"):
                text_content = text_content[3:]
            if text_content.endswith("```"):
                text_content = text_content[:-3]

            parsed_json = json.loads(text_content.strip())
            return response_schema.model_validate(parsed_json)
